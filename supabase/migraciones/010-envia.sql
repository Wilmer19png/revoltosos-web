-- Se puede correr más de una vez sin romper nada.
--
-- · municipios: código DANE de cada ciudad (Envía lo pide para Colombia: 05001 → "05001000").
-- · variantes.peso_g: peso de cada tamaño ya empacado (para cotizar y generar la guía).
-- · ajustes: datos del remitente, la caja que se usa y la transportadora preferida.
-- · pedidos: guía, PDF de la guía, link de rastreo y último estado que reporta Envía.

-- 1. Peso de cada tamaño ------------------------------------------------------------
alter table public.variantes add column if not exists peso_g integer check (peso_g > 0);

-- 2. Datos para Envía --------------------------------------------------------------
alter table public.ajustes add column if not exists envia_remitente jsonb not null default '{}'::jsonb;
  -- {"nombre","empresa","telefono","email","documento","direccion","barrio","departamento","ciudad","referencia"}
alter table public.ajustes add column if not exists envia_caja jsonb not null default '{"largo": 20, "ancho": 15, "alto": 12, "peso_g": 500}'::jsonb;
  -- caja estándar y peso por defecto si un tamaño no tiene peso
alter table public.ajustes add column if not exists envia_transportadoras text;   -- vacío = cotiza con todas
alter table public.ajustes add column if not exists envia_rastreado_en timestamptz;

-- 3. Guía en cada pedido -----------------------------------------------------------
alter table public.pedidos add column if not exists envia_envio_id  text;
alter table public.pedidos add column if not exists envia_servicio  text;
alter table public.pedidos add column if not exists guia_url        text;   -- PDF para imprimir
alter table public.pedidos add column if not exists rastreo_url     text;   -- link para el cliente
alter table public.pedidos add column if not exists envia_estado    text;   -- último estado que reportó Envía
alter table public.pedidos add column if not exists envia_estado_en timestamptz;
alter table public.pedidos add column if not exists novedad         text;   -- dirección errada, no recibió… (para llamar al cliente)
create index if not exists pedidos_guia_idx on public.pedidos (guia) where guia is not null;

-- 4. Municipios con código DANE ------------------------------------------------------
create table if not exists public.municipios (
  departamento text not null,
  municipio    text not null,
  dane         text not null check (dane ~ '^\d{5}$'),
  primary key (departamento, municipio)
);
alter table public.municipios enable row level security;
drop policy if exists "municipios publicos" on public.municipios;
create policy "municipios publicos" on public.municipios for select to anon, authenticated using (true);

